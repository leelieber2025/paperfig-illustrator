  function normalize(lang) {
    lang = String(lang || '').toLowerCase();
    if (lang === 'en' || lang.indexOf('en') === 0) { return 'en'; }
    return 'zh';
  }

  var panelVersion = '';

  function setVersion(v) {
    panelVersion = String(v || '');
  }

  function getVersion() {
    return panelVersion;
  }

  function getLang() {
    try {
      var saved = localStorage.getItem(LANG_KEY);
      if (saved) { return normalize(saved); }
    } catch (ignore) {}
    return DEFAULT_LANG;
  }

  function setLang(lang) {
    lang = normalize(lang);
    try { localStorage.setItem(LANG_KEY, lang); } catch (ignore) {}
    apply(document);
    updateToggle(lang);
    var i;
    for (i = 0; i < listeners.length; i++) {
      try { listeners[i](lang); } catch (ignore) {}
    }
    return lang;
  }

  function t(key, vars) {
    var lang = getLang();
    var table = STRINGS[lang] || STRINGS.zh;
    var s = table[key];
    if (s == null) {
      /* Prefer the other locale over always falling back to Chinese when UI is English. */
      if (lang === 'en') {
        s = (STRINGS.en && STRINGS.en[key]) || (STRINGS.zh && STRINGS.zh[key]) || key;
      } else {
        s = (STRINGS.zh && STRINGS.zh[key]) || (STRINGS.en && STRINGS.en[key]) || key;
      }
    }
    if (!vars) { vars = {}; }
    if ((key === 'banner' || key === 'footer') && vars.version == null && panelVersion) {
      vars = Object.assign({ version: panelVersion }, vars);
    }
    s = String(s).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : '';
    });
    return s;
  }

  function setAttr(el, attr, value) {
    if (value == null) { return; }
    if (attr === 'text') {
      el.textContent = value;
    } else if (attr === 'html') {
      el.innerHTML = value;
    } else {
      el.setAttribute(attr, value);
    }
  }

  function apply(rootEl) {
    var rootNode = rootEl || document;
    var nodes, i, el, key;
    nodes = rootNode.querySelectorAll('[data-i18n]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      key = el.getAttribute('data-i18n');
      if (key) { setAttr(el, 'text', t(key)); }
    }
    nodes = rootNode.querySelectorAll('[data-i18n-html]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      key = el.getAttribute('data-i18n-html');
      if (key) { setAttr(el, 'html', t(key)); }
    }
    nodes = rootNode.querySelectorAll('[data-i18n-title]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      key = el.getAttribute('data-i18n-title');
      if (key) { setAttr(el, 'title', t(key)); }
    }
    nodes = rootNode.querySelectorAll('[data-i18n-placeholder]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      key = el.getAttribute('data-i18n-placeholder');
      if (key) { setAttr(el, 'placeholder', t(key)); }
    }
    nodes = rootNode.querySelectorAll('[data-i18n-aria]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      key = el.getAttribute('data-i18n-aria');
      if (key) { setAttr(el, 'aria-label', t(key)); }
    }
    try { document.documentElement.lang = getLang() === 'en' ? 'en' : 'zh-CN'; } catch (ignore) {}
  }

  function updateToggle(lang) {
    lang = lang || getLang();
    var zhBtn = document.getElementById('langZh');
    var enBtn = document.getElementById('langEn');
    if (zhBtn) {
      zhBtn.classList.toggle('active', lang === 'zh');
      zhBtn.setAttribute('aria-pressed', lang === 'zh' ? 'true' : 'false');
    }
    if (enBtn) {
      enBtn.classList.toggle('active', lang === 'en');
      enBtn.setAttribute('aria-pressed', lang === 'en' ? 'true' : 'false');
    }
  }

  function bindToggle() {
    function click(lang) {
      return function (e) {
        if (e) { e.preventDefault(); }
        setLang(lang);
      };
    }
    var zhBtn = document.getElementById('langZh');
    var enBtn = document.getElementById('langEn');
    if (zhBtn) { zhBtn.addEventListener('click', click('zh')); }
    if (enBtn) { enBtn.addEventListener('click', click('en')); }
    updateToggle(getLang());
  }

  function onChange(cb) {
    if (typeof cb === 'function') { listeners.push(cb); }
  }

  function boot() {
    apply(document);
    bindToggle();
  }


