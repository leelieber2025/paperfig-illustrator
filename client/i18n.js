  function templateToRegex(template) {
    var names = [];
    var parts = String(template || '').split(/\{(\w+)\}/);
    var reStr = '';
    var i;
    for (i = 0; i < parts.length; i++) {
      if (i % 2 === 0) {
        reStr += parts[i].replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      } else {
        names.push(parts[i]);
        reStr += '([\\s\\S]*?)';
      }
    }
    return { re: new RegExp('^' + reStr + '$'), names: names };
  }

  function remapUiStatus(msg) {
    var lang = getLang();
    var other = lang === 'en' ? 'zh' : 'en';
    var keys = UI_STATUS_KEYS;
    var ki, key, locales, li, loc, tpl, packed, m, vars, vi;
    locales = [other, lang];
    for (ki = 0; ki < keys.length; ki++) {
      key = keys[ki];
      for (li = 0; li < locales.length; li++) {
        loc = locales[li];
        tpl = STRINGS[loc] && STRINGS[loc][key];
        if (!tpl || tpl.indexOf('{') < 0 && msg !== tpl) {
          if (tpl && msg === tpl) { return t(key); }
          if (!tpl || tpl.indexOf('{') < 0) { continue; }
        }
        packed = templateToRegex(tpl);
        m = msg.match(packed.re);
        if (!m) { continue; }
        vars = {};
        for (vi = 0; vi < packed.names.length; vi++) {
          vars[packed.names[vi]] = m[vi + 1] != null ? m[vi + 1] : '';
        }
        return t(key, vars);
      }
      /* Exact non-placeholder match for current lang already correct. */
      if (STRINGS[lang] && STRINGS[lang][key] === msg) { return msg; }
    }
    return null;
  }

  function localizeError(message) {
    var msg = String(message == null ? '' : message);
    if (!msg) { return msg; }
    var remapped = remapUiStatus(msg);
    if (remapped != null) { return remapped; }
    var i, pat, m, vars, j, out, prefix;
    for (i = 0; i < ERROR_PATTERNS.length; i++) {
      pat = ERROR_PATTERNS[i];
      m = msg.match(pat.re);
      if (!m) { continue; }
      vars = {};
      if (pat.g) {
        for (j = 0; j < pat.g.length; j++) {
          vars[pat.g[j]] = m[j + 1] != null ? m[j + 1] : '';
        }
      }
      out = t(pat.key, vars);
      if (pat.append) {
        return msg.replace(pat.re, out);
      }
      if (pat.suffix) {
        prefix = msg.slice(0, m.index);
        return localizeError(prefix.replace(/\s+$/, '')) + out;
      }
      return out;
    }
    return msg;
  }

